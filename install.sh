#!/usr/bin/env bash
#
# wrkspc installer + guided setup (macOS, Linux — glibc and musl).
#
# What it does:
#   1. Resolves the release (WRKSPC_VERSION, default: latest) and the
#      platform asset for this machine.
#   2. Downloads the archive and SHA256SUMS, verifies the checksum, and
#      verifies the Sigstore attestation when `gh` is authenticated.
#   3. Installs the binary into ${WRKSPC_INSTALL_DIR:-~/.local/bin}.
#   4. Walks through first-run setup: PKI generation (via openssl),
#      bindings.toml, and the assembled `wrkspc hub run` / `wrkspc node
#      run` commands.
#
# What it does NOT do: write shell dotfiles, store secrets in shell
# variables or files, or start services. Certificates and keys are
# generated by openssl (permissions set by umask) or supplied by you;
# tokens are handled by the wrkspc binary itself (keychain / audited
# sidecar / deployment-unit env). Every step is idempotent and detects
# existing state.
#
# Overrides: WRKSPC_VERSION, WRKSPC_BASE_URL, WRKSPC_INSTALL_DIR,
# WRKSPC_SHARE, WRKSPC_YES, WRKSPC_NO_SETUP, WRKSPC_NO_SKILLS,
# WRKSPC_NO_ATTESTATION — or flags: --yes --no-setup --no-skills
# --no-attestation.
set -euo pipefail

REPO="beardedeagle/wrkspc"
BASE_URL="${WRKSPC_BASE_URL:-https://github.com/beardedeagle/wrkspc/releases/download}"
VERSION="${WRKSPC_VERSION:-latest}"
INSTALL_DIR="${WRKSPC_INSTALL_DIR:-$HOME/.local/bin}"
YES="${WRKSPC_YES:-0}"
NO_SETUP="${WRKSPC_NO_SETUP:-0}"
NO_SKILLS="${WRKSPC_NO_SKILLS:-0}"
NO_ATTESTATION="${WRKSPC_NO_ATTESTATION:-0}"
tmpdir=""

# ---------------------------------------------------------------------------
# Platform detection → release asset name (matches the pipeline's legs).
# ---------------------------------------------------------------------------
detect_target() {
    local os arch
    os="$(uname -s)"
    arch="$(uname -m)"
    case "$os" in
        Darwin)
            case "$arch" in
                arm64|aarch64) echo "wrkspc-aarch64-apple-darwin" ;;
                x86_64) echo "wrkspc-x86_64-apple-darwin" ;;
                *) die "unsupported macOS architecture: $arch" ;;
            esac ;;
        Linux)
            # musl's ldd can exit nonzero even when it prints the
            # banner, and pipefail would then fail the whole probe.
            # Capture the output first, then inspect it.
            local libc="gnu"
            if libc_probe="$(ldd --version 2>&1 || true)" && grep -qi musl <<<"$libc_probe"; then
                libc="musl"
            fi
            case "$arch" in
                x86_64) echo "wrkspc-x86_64-unknown-linux-$libc" ;;
                aarch64|arm64)
                    if [[ "$libc" == "musl" ]]; then
                        die "no ARM64 musl artifact exists in the release matrix — install glibc or build from source"
                    fi
                    echo "wrkspc-aarch64-unknown-linux-gnu" ;;
                *) die "unsupported Linux architecture: $arch" ;;
            esac ;;
        *)
            die "unsupported OS: $os — use install.ps1 on Windows" ;;
    esac
}

die() {
    printf 'install: error: %s\n' "$*" >&2
    exit 1
}

info() { printf '==> %s\n' "$*" >&2; }

# Only letters, digits, dots, hyphens, and underscores: safe for
# certificate subjects/SANs and host ids (never interpreted by a
# shell or parsed as extra openssl extensions).
valid_name() {
    [[ "$1" =~ ^[A-Za-z0-9._-]+$ ]]
}

# Escape a value for a TOML basic string (" and \ only; the values
# never contain control characters because ask() strips nothing but
# they come from a single read line).
toml_escape() {
    printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

ask() {
    # ask <prompt> <default> — honors WRKSPC_YES (returns the default).
    # The prompt goes to stderr; stdout carries ONLY the answer, since
    # every caller captures ask with command substitution and a prompt
    # in the capture would poison the equality checks.
    local prompt="$1" default="$2" answer
    if [[ "$YES" == "1" ]]; then
        echo "$default"
        return
    fi
    printf '%s [%s] ' "$prompt" "$default" >&2
    read -r answer
    echo "${answer:-$default}"
}

resolve_version() {
    if [[ "$VERSION" != "latest" ]]; then
        echo "$VERSION"
        return
    fi
    if [[ "$BASE_URL" != https://github.com/*/releases/download ]]; then
        die "WRKSPC_VERSION is required when WRKSPC_BASE_URL is overridden"
    fi
    info "resolving latest release"
    local tag
    tag="$(curl -fsSL "https://api.github.com/repos/$REPO/releases/latest" \
        | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -1)"
    [[ -n "$tag" ]] || die "no published release found for $REPO"
    echo "$tag"
}

sha256_of() {
    # sha256_of <file> — sha256sum on Linux, shasum on macOS/BSD.
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    else
        shasum -a 256 "$1" | awk '{print $1}'
    fi
}

# ---------------------------------------------------------------------------
# Fetch + verify + install
# ---------------------------------------------------------------------------
install_binary() {
    local target version archive
    target="$(detect_target)"
    version="$(resolve_version)"
    case "$target" in
        *windows*) die "this script does not handle Windows — use install.ps1" ;;
        *) archive="$target.tar.gz" ;;
    esac

    tmpdir="$(mktemp -d)"
    trap 'if [[ -n "$tmpdir" ]]; then rm -rf "$tmpdir"; fi' EXIT

    info "downloading $archive ($version)"
    curl -fsSL -o "$tmpdir/SHA256SUMS" "$BASE_URL/$version/SHA256SUMS"
    curl -fsSL -o "$tmpdir/$archive" "$BASE_URL/$version/$archive"

    info "verifying checksum"
    local expected actual
    expected="$(awk -v f="$archive" '$2 == f { print $1 }' "$tmpdir/SHA256SUMS")"
    [[ -n "$expected" ]] || die "$archive is missing from SHA256SUMS"
    actual="$(sha256_of "$tmpdir/$archive")"
    [[ "$expected" == "$actual" ]] || die "checksum mismatch for $archive"

    if [[ "$NO_ATTESTATION" != "1" ]] && command -v gh >/dev/null 2>&1 \
        && gh auth status >/dev/null 2>&1; then
        info "verifying Sigstore attestation"
        (cd "$tmpdir" && gh attestation verify "$archive" --repo "$REPO") \
            || die "attestation verification failed — refusing to install"
    elif [[ "$NO_ATTESTATION" != "1" ]]; then
        info "gh not authenticated — attestation skipped (checksum still verified)"
    fi

    info "extracting"
    tar -xzf "$tmpdir/$archive" -C "$tmpdir"
    [[ -x "$tmpdir/wrkspc" ]] || die "archive does not contain the wrkspc binary"

    mkdir -p "$INSTALL_DIR"
    install -m 0755 "$tmpdir/wrkspc" "$INSTALL_DIR/wrkspc"
    info "installed to $INSTALL_DIR/wrkspc"
    "$INSTALL_DIR/wrkspc" --version

    if [[ ":$PATH:" != *":$INSTALL_DIR:"* ]]; then
        printf 'note: %s is not on PATH — add it with:\n' "$INSTALL_DIR" >&2
        # shellcheck disable=SC2016  # the literal $PATH is the hint's point
        printf '      export PATH="%s:$PATH"\n' "$INSTALL_DIR" >&2
    fi
}

# ---------------------------------------------------------------------------
# Guided setup: PKI, bindings, assembled run commands. The wrkspc binary
# owns secrets; openssl only generates certificate material with umask 077.
# ---------------------------------------------------------------------------
WRKSPC_SHARE="${WRKSPC_SHARE:-$HOME/.local/share/wrkspc}"
PKI_DIR="$WRKSPC_SHARE/pki"

setup_pki() {
    local proceed
    proceed="$(ask "Generate a CA and node/hub certificates? (y/n)" "y")"
    [[ "$proceed" == "y" ]] || return 0

    command -v openssl >/dev/null 2>&1 \
        || die "openssl is required for PKI generation — install it or bring your own certificates"

    mkdir -p "$PKI_DIR"
    (
        umask 077
        if [[ -f "$PKI_DIR/ca.pem" ]]; then
            local reuse
            reuse="$(ask "CA already exists at $PKI_DIR/ca.pem — reuse it? (y/n)" "y")"
            [[ "$reuse" != "y" ]] && return 0
        else
            local ca_cn ca_days
            ca_cn="$(ask "CA common name" "wrkspc-ca")"
            valid_name "$ca_cn" || die "invalid common name: $ca_cn"
            ca_days="$(ask "CA validity in days" "3650")"
            [[ "$ca_days" =~ ^[0-9]+$ ]] || die "invalid validity period: $ca_days"
            openssl genrsa -out "$PKI_DIR/ca.key" 4096
            openssl req -x509 -new -nodes \
                -key "$PKI_DIR/ca.key" -sha256 -days "$ca_days" \
                -subj "/CN=$ca_cn" -out "$PKI_DIR/ca.pem"
            info "CA written to $PKI_DIR (ca.pem, ca.key)"
        fi

        if [[ ! -f "$PKI_DIR/hub.crt" ]]; then
            local hub_host
            hub_host="$(ask "Hub hostname (the --card-url name; certificate SAN)" "hub.example.com")"
            valid_name "$hub_host" || die "invalid hub hostname: $hub_host"
            openssl genrsa -out "$PKI_DIR/hub.key" 2048
            openssl req -new -key "$PKI_DIR/hub.key" -subj "/CN=$hub_host" \
                -addext "subjectAltName=DNS:$hub_host" -out "$PKI_DIR/hub.csr"
            # x509 -req drops CSR extensions by default, and the
            # -copy_extensions flag does not exist in LibreSSL
            # (/usr/bin/openssl on macOS). -extfile with the SAN
            # extension is the portable form.
            openssl x509 -req -in "$PKI_DIR/hub.csr" -CA "$PKI_DIR/ca.pem" \
                -CAkey "$PKI_DIR/ca.key" -CAcreateserial -days 825 \
                -extfile <(printf 'subjectAltName=DNS:%s\n' "$hub_host") \
                -sha256 -out "$PKI_DIR/hub.crt"
            rm -f "$PKI_DIR/hub.csr"
            info "hub certificate written ($PKI_DIR/hub.crt, $PKI_DIR/hub.key)"
        fi

        if [[ ! -f "$PKI_DIR/node.crt" ]]; then
            local host_id
            host_id="$(ask "Node host id (the client certificate SAN)" "this-machine.example")"
            valid_name "$host_id" || die "invalid node host id: $host_id"
            openssl genrsa -out "$PKI_DIR/node.key" 2048
            openssl req -new -key "$PKI_DIR/node.key" -subj "/CN=$host_id" \
                -addext "subjectAltName=DNS:$host_id" -out "$PKI_DIR/node.csr"
            openssl x509 -req -in "$PKI_DIR/node.csr" -CA "$PKI_DIR/ca.pem" \
                -CAkey "$PKI_DIR/ca.key" -CAcreateserial -days 825 \
                -extfile <(printf 'subjectAltName=DNS:%s\n' "$host_id") \
                -sha256 -out "$PKI_DIR/node.crt"
            rm -f "$PKI_DIR/node.csr"
            info "node certificate written ($PKI_DIR/node.crt, $PKI_DIR/node.key)"
        fi
    )
}

setup_node() {
    local proceed
    proceed="$(ask "Set up a node here? (y/n)" "y")"
    [[ "$proceed" == "y" ]] || return 0

    local node_dir="$WRKSPC_SHARE/node"
    mkdir -p "$node_dir"

    if [[ -f "$node_dir/bindings.toml" ]]; then
        local keep
        keep="$(ask "bindings.toml exists — keep it? (n regenerates)" "y")"
        if [[ "$keep" == "y" ]]; then
            info "keeping $node_dir/bindings.toml"
            return 0
        fi
    fi
    {
        local harness cwd adapter
        harness="$(ask "Harness to bind (codex|claude|gemini|pi|qwen|kimi|mcode)" "codex")"
        cwd="$(ask "Project directory for the binding (cwd)" "$HOME")"
        case "$harness" in
            codex) adapter="npx -y @agentclientprotocol/codex-acp@2.1.1" ;;
            claude) adapter="npx -y @agentclientprotocol/claude-agent-acp" ;;
            *) adapter="$(ask "Adapter command for $harness" "")" ;;
        esac
        cat > "$node_dir/bindings.toml" <<EOF
[[binding]]
peer_id = "$(toml_escape "$harness")"
harness = "$(toml_escape "$harness")"
cwd = "$(toml_escape "$cwd")"
command = "$(toml_escape "$adapter")"
EOF
    }
    info "bindings.toml written to $node_dir/bindings.toml"

    local hub_url host_id
    hub_url="$(ask "Hub URL (the node dials this over mTLS)" "https://hub.example.com:8443")"
    host_id="$(ask "Node host id (must match the client certificate SAN)" "this-machine.example")"

    info "the node is started with (once the hub is reachable):"
    cat <<EOF
    wrkspc node run \\
        --db $(printf '%q' "$node_dir/node.db") \\
        --bindings $(printf '%q' "$node_dir/bindings.toml") \\
        --hub $(printf '%q' "$hub_url") \\
        --host-id $(printf '%q' "$host_id") \\
        --tls-cert $(printf '%q' "$PKI_DIR/node.crt") \\
        --tls-key $(printf '%q' "$PKI_DIR/node.key") \\
        --tls-ca $(printf '%q' "$PKI_DIR/ca.pem")
EOF
}

setup_hub() {
    local proceed
    proceed="$(ask "Run the hub on this machine too? (y/n)" "n")"
    [[ "$proceed" == "y" ]] || return 0

    local db card_url bind
    db="$(ask "Hub database path" "$WRKSPC_SHARE/hub/hub.db")"
    mkdir -p "$(dirname "$db")"
    card_url="$(ask "External card URL (must match the hub certificate)" "https://hub.example.com:8443")"
    bind="$(ask "A2A/UI listener bind address" "0.0.0.0:8443")"

    info "the hub is started with:"
    cat <<EOF
    wrkspc hub run \\
        --db $(printf '%q' "$db") \\
        --a2a $(printf '%q' "$bind") \\
        --card-url $(printf '%q' "$card_url") \\
        --tls-cert $(printf '%q' "$PKI_DIR/hub.crt") \\
        --tls-key $(printf '%q' "$PKI_DIR/hub.key") \\
        --tls-ca $(printf '%q' "$PKI_DIR/ca.pem")
EOF
}

setup_skills() {
    local proceed
    proceed="$(ask "Install the wrkspc skill into a harness now? (y/n)" "y")"
    [[ "$proceed" == "y" ]] || return 0
    local harness skill_id
    harness="$(ask "Harness for the skill install" "codex")"
    # The binding short names differ from the registry ids the skill
    # installer resolves (registry.rs): map them before invoking.
    case "$harness" in
        claude) skill_id="claude-code" ;;
        gemini) skill_id="gemini-cli" ;;
        qwen) skill_id="qwen-code" ;;
        kimi) skill_id="kimi-code-cli" ;;
        mcode) skill_id="minimax-code" ;;
        *) skill_id="$harness" ;;
    esac
    "$INSTALL_DIR/wrkspc" skill install --harness "$skill_id" || true
}

token_pointer() {
    cat <<'EOF'
UI token: the operator UI's bearer token is managed by wrkspc itself —
on macOS it lives in the Keychain (run `wrkspc ui-token` to copy it),
elsewhere it is stored beside the hub database with 0600 permissions
(`wrkspc ui-token --db <hub db>`). For a supervised/container hub, put
WRKSPC_UI_TOKEN in the service unit's environment, never a shell
dotfile — the env override is authoritative while set.
EOF
}

# ---------------------------------------------------------------------------
main() {
    for arg in "$@"; do
        case "$arg" in
            --yes) YES=1 ;;
            --no-setup) NO_SETUP=1 ;;
            --no-skills) NO_SKILLS=1 ;;
            --no-attestation) NO_ATTESTATION=1 ;;
            *) die "unknown argument: $arg" ;;
        esac
    done
    # The wizard needs a terminal: piping curl|sh gives `read` an EOF
    # that dies under set -e at the first prompt. Refuse the pipe form
    # unless it is explicitly non-interactive.
    if [[ "$NO_SETUP" != "1" && "$YES" != "1" && ! -t 0 ]]; then
        die "interactive prompts need a terminal — download and run the script, or pipe it with --yes"
    fi
    info "wrkspc installer — $REPO"
    install_binary
    if [[ "$NO_SETUP" != "1" ]]; then
        setup_pki
        setup_hub
        setup_node
        if [[ "$NO_SKILLS" != "1" ]]; then
            setup_skills
        fi
        token_pointer
    fi
    info "done — see https://beardedeagle.github.io/wrkspc/getting-started/quick-start.html"
}

main "$@"
